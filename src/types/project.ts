/**
 * Project Model Types
 *
 * The ProjectModel is the central data structure produced by the discovery
 * subsystem. Every future milestone — scanning, parsing, rule execution,
 * reporting — depends on this model. It represents everything the tool knows
 * about the React Native / Expo project being audited.
 *
 * Design principle: model what IS, not what we WISH. The model describes the
 * project as discovered, not as configured. For example, `packageManager` is
 * detected from lock files, not read from a user preference.
 *
 * @module types/project
 */

// ---------------------------------------------------------------------------
// Project classification
// ---------------------------------------------------------------------------

/**
 * The high-level framework used by the project.
 *
 * This is the primary axis of classification. Rules use this to determine
 * which analysis strategies apply. For example, Expo-specific rules only
 * activate when the framework is `Expo`.
 */
export enum ProjectFramework {
  /** Project uses `expo` as its build tool and runtime. */
  Expo = "expo",
  /** Project uses the React Native CLI and bare workflow. */
  ReactNativeCLI = "react-native-cli",
}

/**
 * The Expo workflow. Only meaningful when {@link ProjectFramework} is `Expo`.
 *
 * - **Managed**: The project does not have native `ios/` and `android/`
 *   directories. Native code is generated by Expo at build time. The developer
 *   writes only JavaScript/TypeScript.
 * - **Bare**: The project has native `ios/` and `android/` directories.
 *   The developer can write custom native code alongside JavaScript. Expo
 *   modules are used via the `expo` package but the native shell is
 *   user-controlled.
 */
export enum ExpoWorkflow {
  Managed = "managed",
  Bare = "bare",
}

/**
 * The package manager detected in the project.
 *
 * Detected from lock files, not from configuration. This is what the project
 * *actually* uses, which may differ from what a developer claims to use.
 */
export enum PackageManager {
  Npm = "npm",
  Yarn = "yarn",
  Pnpm = "pnpm",
  /** Package manager could not be determined (no lock file found). */
  Unknown = "unknown",
}

// ---------------------------------------------------------------------------
// Dependency & metadata types
// ---------------------------------------------------------------------------

/**
 * A flat map of package name → semver range.
 *
 * Example: `{ "react-native": "0.76.0", "expo": "~52.0.0" }`
 */
export type DependencyMap = Record<string, string>;

// ---------------------------------------------------------------------------
// Configuration file discovery
// ---------------------------------------------------------------------------

/**
 * Paths to configuration files discovered in the project.
 *
 * Every value is either:
 * - An **absolute path** (string) — the file exists at this location.
 * - `null` — we checked and the file does not exist in this project.
 *
 * `null` is intentionally distinct from `undefined`:
 * - `null` = "looked, not there"
 * - `undefined` = "haven't checked yet" (only relevant internally)
 */
export interface ConfigFiles {
  /** Absolute path to `package.json`. Always present for a valid project. */
  packageJson: string;

  /**
   * TypeScript configuration file.
   * Priority order checked: `tsconfig.json` (project root only for Phase 1).
   */
  tsconfig: string | null;

  /**
   * Babel configuration file.
   * Priority order checked: `babel.config.js`, `babel.config.cjs`,
   * `babel.config.mjs`, `.babelrc`.
   */
  babelConfig: string | null;

  /**
   * Metro bundler configuration.
   * Checked: `metro.config.js`, `metro.config.cjs`, `metro.config.mjs`.
   */
  metroConfig: string | null;

  /**
   * Expo static configuration file (`app.json`).
   * Only relevant for Expo projects. Contains the `expo` key with
   * app metadata, plugins, and EAS configuration.
   */
  appJson: string | null;

  /**
   * Expo dynamic configuration file.
   * Checked: `app.config.js`, `app.config.ts`.
   * A JavaScript/TypeScript file that exports a configuration object.
   * Takes precedence over `appJson` if both exist.
   */
  appConfig: string | null;

  /**
   * Expo environment type declarations.
   * Generated by Expo to provide TypeScript types for environment
   * variables and app configuration.
   */
  expoEnvDts: string | null;

  /**
   * Tailwind CSS configuration file.
   * Checked: `tailwind.config.js`, `tailwind.config.ts`, `tailwind.config.cjs`.
   */
  tailwindConfig: string | null;

  /**
   * NativeWind configuration file.
   * Checked: `nativewind.config.js`, `nativewind.config.ts`.
   * NativeWind is a popular Tailwind CSS port for React Native.
   */
  nativewindConfig: string | null;

  /**
   * ESLint configuration file.
   * Checked (flat config first, then legacy):
   * `eslint.config.js`, `eslint.config.mjs`, `eslint.config.cjs`,
   * `.eslintrc.js`, `.eslintrc.json`, `.eslintrc.yaml`, `.eslintrc.yml`.
   */
  eslintConfig: string | null;
}

// ---------------------------------------------------------------------------
// The Project Model
// ---------------------------------------------------------------------------

/**
 * The central data structure representing a discovered React Native project.
 *
 * Produced by {@link discoverProject} in the discovery subsystem.
 * Consumed by: scanner (file discovery patterns), parser (tsconfig paths),
 * engine (rule filtering by framework), reporter (project metadata in output).
 *
 * Every field is populated during discovery. No field requires a second pass.
 */
export interface ProjectModel {
  // -- Identity -----------------------------------------------------------

  /** Absolute path to the project root directory (where package.json lives). */
  root: string;

  /** Package name from package.json (`name` field). */
  name: string;

  /** Package version from package.json (`version` field). */
  version: string;

  // -- Classification -----------------------------------------------------

  /** High-level framework: Expo or React Native CLI. */
  framework: ProjectFramework;

  /**
   * Whether rn-audit supports this project.
   *
   * Currently `true` for all React Native and Expo projects.
   * In the future, may be `false` for projects with incompatible
   * React Native versions or experimental configurations.
   */
  isSupported: boolean;

  /**
   * The Expo workflow: managed or bare.
   * `undefined` when {@link framework} is not `Expo`.
   */
  workflow?: ExpoWorkflow;

  /**
   * Whether the project uses Expo Router for file-based routing.
   * Detected by the presence of `expo-router` in dependencies.
   */
  hasExpoRouter: boolean;

  // -- Runtime versions ---------------------------------------------------

  /** Installed React Native version (from dependencies). e.g., `"0.76.0"` */
  reactNativeVersion: string | null;

  /** Installed Expo SDK version (from dependencies). e.g., `"52.0.0"` */
  expoVersion: string | null;

  /** Installed React version (from dependencies). e.g., `"18.3.1"` */
  reactVersion: string | null;

  /**
   * Installed TypeScript version (from devDependencies or dependencies).
   * `null` if the project is plain JavaScript.
   */
  typescriptVersion: string | null;

  /**
   * The Node.js version required by the project (from `engines.node`).
   * e.g., `">=18"`. `null` if no engine constraint is declared.
   */
  nodeEngine: string | null;

  // -- Package manager ----------------------------------------------------

  /** The detected package manager. */
  packageManager: PackageManager;

  // -- Dependencies -------------------------------------------------------

  /** Production dependencies from package.json (`dependencies`). */
  dependencies: DependencyMap;

  /** Development dependencies from package.json (`devDependencies`). */
  devDependencies: DependencyMap;

  // -- Configuration files ------------------------------------------------

  /** Paths to all discovered configuration files. */
  configFiles: ConfigFiles;

  // -- Monorepo (future) --------------------------------------------------

  /**
   * Whether this project is part of a monorepo workspace.
   * Detected by the presence of a workspace root above the project root.
   * Phase 2 feature — always `false` in Phase 1.
   */
  isWorkspace: boolean;

  /**
   * If this project is part of a workspace, the absolute path to the
   * workspace root (the directory containing the workspace config).
   * Phase 2 feature — always `null` in Phase 1.
   */
  workspaceRoot: string | null;

  // -- Metadata -----------------------------------------------------------

  /** ISO 8601 timestamp of when discovery was performed. */
  discoveredAt: string;
}
